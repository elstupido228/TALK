// Справочник «ID клиента → наименование и ИНН» для «Мониторинга». ID (КЛ-0001…) — служебный, на экране его нет:
// пользователь видит наименование и ИНН. Порядок поиска: справочник клиентов портала (clients.client_code = ID),
// столбцы «Наименование» и «ИНН» загруженной выгрузки, для условного портфеля — условные наименования и ИНН.
// Условные ИНН — 000001NNNN (NNNN — номер ID): заведомо несуществующие, отличаются от ИНН условных сделок 000000000N.
const SHORT = {
  "Грузоперевозки": "Транс", "Строительство": "Строй", "Оптовая торговля": "Торг", "Сельское хозяйство": "Агро",
  "Обрабатывающее производство": "Пром", "Добыча полезных ископаемых": "Ресурс",
};
const num = (id) => (String(id).match(/(\d+)$/) || [])[1] || null;

// условные реквизиты клиента демо-портфеля (портфель сгенерирован, реальных организаций за ним нет)
function demoParty(id, sector) {
  const n = num(id);
  if (!n) return null;
  return { name: `ООО «Пример-${SHORT[sector] || "Лизинг"} ${+n}»`, inn: "000001" + n.padStart(4, "0").slice(-4), conditional: true };
}

module.exports = { demoParty };
