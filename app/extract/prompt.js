// Промпт распознавания отчётности. Перенесён из страницы калькулятора (seed/calc/page.src.html) без изменения текста.
function prompt(name,from,to,total){
  return `Ты извлекаешь данные из российской бухгалтерской отчётности по РСБУ (формы по ОКУД 0710001 «Бухгалтерский баланс» и 0710002 «Отчёт о финансовых результатах»).
Файл: «${name}». Приложены изображения страниц ${from}–${to} из ${total}. Часть страниц может быть квитанциями ЭДО без таблиц — их пропусти.

Для каждой числовой графы таблиц (отчётная дата и сравнительные графы) выпиши значения строк с кодами:
баланс: 1200, 1230, 1240, 1250, 1300, 1370, 1500, 1530, 1540, 1550, 1600, 1700;
отчёт о финансовых результатах: 2110, 2200, 2400.
Правила: значения в тыс. руб. как напечатаны; число в скобках — отрицательное; прочерк — 0; строки нет в документе — null. Не вычисляй и не подставляй значения, которых нет на изображении. Номер страницы — порядковый номер изображения в этом файле (от ${from}).

Ответь только JSON:
{"company":"наименование организации или null","inn":"ИНН организации или null",
 "form_variant":"standard" — полная форма или "simplified" — упрощённая (в заголовке «упрощённая», строки укрупнены),
 "confirmation":"fns_receipt" — есть квитанция/подтверждение ФНС или оператора ЭДО о приёме; "edo_signature" — отметка о подписании электронной подписью или передаче через ЭДО (Диадок, СБИС и т.п.); "paper_signature" — подпись руководителя и печать на скане; "none" — ничего из перечисленного,
 "columns":[{"kind":"balance" или "pnl","header":"заголовок графы как в документе","date":"ДД.ММ.ГГГГ — дата баланса или последний день отчётного периода","months":число месяцев периода для pnl (3, 6, 9, 12) или null,"values":{"1200":706837,...},"page":{"1200":2,...}}]}
Если на страницах нет таблиц баланса или отчёта о финансовых результатах, верни {"company":null,"inn":null,"form_variant":null,"confirmation":квитанция или подпись, если видна, иначе null,"columns":[]}.`;
}

module.exports = { prompt };
